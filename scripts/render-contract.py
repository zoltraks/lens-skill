"""Regenerate the contract enumeration block in `process/report-contract.md`.

The marked block between ``<!-- contract:begin -->`` and ``<!-- contract:end -->``
renders the live enumerations dumped by ``validate-report.py --dump-contract`` -
canonical scorecard dimensions and their model ids, Document Information fields,
Health Dashboard markers, run-state vocabulary, and the PAR row range - so the
documented contract cannot drift from the mechanically enforced one.

Usage:
  python render-contract.py [<contract.md>]
  python render-contract.py --check [<contract.md>]

Without ``--check`` the block is rewritten in place and the result prints.
``--check`` exits 1 when the checked-in block differs from a fresh render,
naming it as contract drift to regenerate.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- contract:begin -->"
END = "<!-- contract:end -->"


def load_contract(script_dir: Path) -> dict:
    validator = script_dir / "validate-report.py"
    completed = subprocess.run(
        [sys.executable, str(validator), "--dump-contract"],
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise SystemExit(
            f"validate-report.py --dump-contract failed: {completed.stderr.strip()}"
        )
    return json.loads(completed.stdout)


def render(contract: dict) -> str:
    """The generated enumeration block, markers included."""
    dimensions = contract["scorecard_dimensions"]
    ids = contract["dimension_ids"]
    doc = contract["doc_info"]
    state = contract["run_state"]
    markers = contract["health_dashboard_markers"]
    par = contract["par_rows"]
    optional = [f for f in doc["allowed"] if f not in doc["required"]]
    lines = [
        BEGIN,
        "",
        "Generated by `scripts/render-contract.py` - edit `scripts/validate-report.py`,",
        "then rerun the renderer. Do not edit inside the markers.",
        "",
        "### Canonical Dimensions",
        "",
        "Scorecard display names in canonical order and the `audit-model.json`",
        "dimension key each maps to:",
        "",
        "| #  | Scorecard name        | Model id              |",
        "|----|-----------------------|-----------------------|",
    ]
    for index, (name, ident) in enumerate(zip(dimensions, ids), 1):
        lines.append(f"| {index:<2} | {name:<21} | {ident:<21} |")
    lines += [
        "",
        "Multi-project models prefix each key - `<project>.security`.",
        "",
        "### Document Information Fields",
        "",
        f"Required rows: {', '.join(f'`{f}`' for f in doc['required'])}.",
        "",
        f"Optional rows: {', '.join(f'`{f}`' for f in optional)}.",
        "",
        "### Health Dashboard Markers",
        "",
        f"Every Health Dashboard section carries: {', '.join(f'`{m}`' for m in markers)}.",
        "",
        "### Run State",
        "",
        f"`work/audit-state.json` carries `state_version` {state['state_version']} and",
        "this vocabulary:",
        "",
        f"- Phases in order: {', '.join(f'`{p}`' for p in state['phases'])}.",
        f"- Gate tiers: {', '.join(f'`{t}`' for t in state['gate_tiers'])}.",
        f"- Required gates: {', '.join(f'`{g}`' for g in state['required_gates'])}.",
        f"- Artifact kinds: {', '.join(f'`{k}`' for k in state['artifact_kinds'])}.",
        "",
        "### Validation Protocol",
        "",
        f"Rows `PAR-1` through `PAR-{par}` in fixed order.",
        "",
        END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    paths = [a for a in argv[1:] if not a.startswith("-")]
    script_dir = Path(__file__).resolve().parent
    target = (
        Path(paths[0]) if paths
        else script_dir.parent / "process" / "report-contract.md"
    )
    if target.is_dir():
        target = target / "report-contract.md"
    if not target.is_file():
        print(f"contract file not found: {target}")
        return 1
    text = target.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{target.name} has no {BEGIN} / {END} markers")
        return 1
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    block = render(load_contract(script_dir))
    if check:
        if text[start:end] == block:
            print(f"PASS {target.name} contract block is current")
            return 0
        print(
            f"FAIL {target.name} contract block is stale - rerun "
            f"scripts/render-contract.py {target}"
        )
        return 1
    target.write_text(text[:start] + block + text[end:], encoding="utf-8")
    print(f"rendered contract block in {target.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
