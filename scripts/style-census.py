#!/usr/bin/env python3
"""Deterministic identifier-shape census for the code-style assessment.

Walks a repository, classifies every declaration it can see by identifier
kind and casing shape, and reports the dominant shape share per partition
(language plus top-level directory).

Reads files as data only - it never executes, builds, or analyzes the
subject, and two runs on the same tree produce identical output.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

GENERATED_MARKERS = (
    "@generated",
    "auto-generated",
    "autogenerated",
    "code generated",
    "do not edit",
    "automatically generated",
)

GENERATED_DIRS = (
    ".git",
    "node_modules",
    "vendor",
    "third_party",
    "third-party",
    "dist",
    "build",
    "out",
    "target",
    "__pycache__",
    ".venv",
    "venv",
    "coverage",
)

LANGUAGE_BY_EXT = {
    ".ts": "typescript", ".tsx": "typescript", ".js": "javascript",
    ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".py": "python", ".rs": "rust", ".go": "go", ".java": "java",
    ".cs": "csharp", ".kt": "kotlin", ".kts": "kotlin",
    ".rb": "ruby", ".php": "php", ".swift": "swift", ".zig": "zig",
    ".c": "c", ".h": "c-family", ".cc": "cpp", ".cpp": "cpp",
    ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp",
    ".sh": "shell", ".bash": "shell", ".sql": "sql",
    ".pas": "pascal", ".pp": "pascal",
    ".asm": "assembly", ".s": "assembly", ".inc": "assembly",
    ".fpc": "pascal",
}

# Each pattern carries the identifier kind and a regex whose group 1 holds
# the declared name. Patterns are declaration-shaped, not keyword searches.
PATTERNS = {
    "python": [
        ("type", re.compile(r"^\s*class\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:async\s+)?def\s+([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*([A-Za-z_][\w]*)\s*[:=]")),
    ],
    "typescript": [
        ("type", re.compile(r"^\s*(?:export\s+)?(?:declare\s+)?(?:abstract\s+)?(?:class|interface|type|enum)\s+([A-Za-z_$][\w$]*)")),
        ("function", re.compile(r"^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)")),
        ("variable", re.compile(r"^\s*(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)")),
    ],
    "javascript": [
        ("type", re.compile(r"^\s*(?:export\s+)?class\s+([A-Za-z_$][\w$]*)")),
        ("function", re.compile(r"^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)")),
        ("variable", re.compile(r"^\s*(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)")),
    ],
    "rust": [
        ("type", re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:struct|enum|trait|union|type)\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const|static)\s+([A-Za-z_][\w]*)")),
    ],
    "go": [
        ("type", re.compile(r"^\s*type\s+([A-Za-z_][\w]*)\s+(?:struct|interface|[A-Za-z_])")),
        ("function", re.compile(r"^func\s+(?:\([^)]*\)\s*)?([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*(?:var|const)\s+([A-Za-z_][\w]*)")),
    ],
    "java": [
        ("type", re.compile(r"^\s*(?:public|private|protected|abstract|final|static|\s)*\s*(?:class|interface|enum|record|@interface)\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:public|private|protected|static|final|synchronized|abstract|\s)+[\w<>\[\],.?]+\s+([a-zA-Z_][\w]*)\s*\(")),
    ],
    "csharp": [
        ("type", re.compile(r"^\s*(?:public|private|protected|internal|sealed|abstract|static|partial|\s)*\s*(?:class|interface|enum|struct|record)\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:public|private|protected|internal|static|virtual|override|async|sealed|partial|extern|\s)+[\w<>\[\],.?]+\s+([A-Za-z_][\w]*)\s*\(")),
    ],
    "kotlin": [
        ("type", re.compile(r"^\s*(?:public|private|internal|sealed|abstract|data|open|\s)*\s*(?:class|interface|object|enum)\s+(?:class\s+)?([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:override\s+)?(?:suspend\s+)?fun\s+(?:[\w.]+\.)?([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*(?:private\s+)?(?:val|var)\s+([A-Za-z_][\w]*)")),
    ],
    "ruby": [
        ("type", re.compile(r"^\s*class\s+([A-Za-z_][\w:]*)|^\s*module\s+([A-Za-z_][\w:]*)")),
        ("function", re.compile(r"^\s*def\s+(?:self\.)?([A-Za-z_][\w?!]*)")),
        ("variable", re.compile(r"^\s*([A-Za-z_][\w]*)\s*=")),
    ],
    "php": [
        ("type", re.compile(r"^\s*(?:abstract\s+|final\s+)?(?:class|interface|trait|enum)\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:public|private|protected|static|\s)*\s*function\s+([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*(?:const)\s+([A-Za-z_][\w]*)")),
    ],
    "swift": [
        ("type", re.compile(r"^\s*(?:public|private|internal|open|final|\s)*\s*(?:class|struct|enum|protocol|extension)\s+([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^\s*(?:public|private|internal|open|static|class|mutating|\s)*\s*func\s+([A-Za-z_][\w]*)")),
    ],
    "zig": [
        ("type", re.compile(r"^\s*(?:pub\s+)?const\s+([A-Za-z_][\w]*)\s*=\s*(?:struct|enum|union|opaque)")),
        ("function", re.compile(r"^\s*(?:pub\s+)?(?:export\s+)?fn\s+([A-Za-z_][\w]*)")),
        ("variable", re.compile(r"^\s*(?:pub\s+)?(?:const|var)\s+([A-Za-z_][\w]*)")),
    ],
    "c": [
        ("function", re.compile(r"^(?:static\s+)?[A-Za-z_][\w\s\*]+\s+([A-Za-z_][\w]*)\s*\([^;]*\)\s*$")),
        ("variable", re.compile(r"^#\s*define\s+([A-Za-z_][\w]*)")),
        ("type", re.compile(r"^\s*(?:typedef\s+)?(?:struct|enum|union)\s+([A-Za-z_][\w]*)")),
    ],
    "c-family": [
        ("function", re.compile(r"^(?:static\s+)?[A-Za-z_][\w\s\*]+\s+([A-Za-z_][\w]*)\s*\([^;]*\)\s*$")),
        ("variable", re.compile(r"^#\s*define\s+([A-Za-z_][\w]*)")),
        ("type", re.compile(r"^\s*(?:typedef\s+)?(?:struct|enum|union)\s+([A-Za-z_][\w]*)")),
    ],
    "cpp": [
        ("type", re.compile(r"^\s*(?:template\s*<[^>]*>\s*)?(?:class|struct|enum|union)\s+(?:class\s+)?([A-Za-z_][\w]*)")),
        ("function", re.compile(r"^(?:static\s+|inline\s+|constexpr\s+|virtual\s+)*[A-Za-z_][\w:<>\s\*&]+\s+([A-Za-z_][\w]*)\s*\([^;]*\)\s*(?:const\s*)?(?:noexcept\s*)?\{?\s*$")),
        ("variable", re.compile(r"^#\s*define\s+([A-Za-z_][\w]*)")),
    ],
    "shell": [
        ("function", re.compile(r"^\s*(?:function\s+)?([A-Za-z_][\w]*)\s*\(\s*\)")),
        ("variable", re.compile(r"^([A-Za-z_][\w]*)=")),
    ],
    "sql": [
        ("type", re.compile(r"(?i)^\s*create\s+(?:or\s+replace\s+)?(?:table|view)\s+(?:if\s+not\s+exists\s+)?([A-Za-z_][\w.]*)")),
        ("function", re.compile(r"(?i)^\s*create\s+(?:or\s+replace\s+)?(?:function|procedure)\s+([A-Za-z_][\w.]*)")),
    ],
    "pascal": [
        ("type", re.compile(r"(?i)^\s*([A-Za-z_][\w]*)\s*=\s*(?:class|record|interface|object|set\s+of|array)")),
        ("function", re.compile(r"(?i)^\s*(?:function|procedure|constructor|destructor)\s+([A-Za-z_][\w.]*)")),
    ],
    "assembly": [
        ("label", re.compile(r"^([A-Za-z_.$][\w.$]*):")),
        ("variable", re.compile(r"^\s*([A-Za-z_][\w]*)\s*(?:=|equ|EQU|:=)\s")),
    ],
}

PREFIX_RULES = (
    (re.compile(r"^I[A-Z][\w]*$"), "I-prefixed"),
    (re.compile(r"^_+[\w]+$"), "underscore-prefixed"),
    (re.compile(r"^m_[\w]+$"), "m_-prefixed"),
    (re.compile(r"^s_[\w]+$"), "s_-prefixed"),
    (re.compile(r"^k[A-Z][\w]*$"), "k-prefixed"),
    (re.compile(r"^ps[A-Z][\w]*$"), "type-prefixed"),
)

SUFFIX_RULES = (
    (re.compile(r"[\w]+Impl$"), "Impl-suffixed"),
    (re.compile(r"[\w]+Async$"), "Async-suffixed"),
    (re.compile(r"[\w]+_t$"), "_t-suffixed"),
)


def classify(name: str) -> str:
    """Classify an identifier into a casing-shape family."""
    base = name.lstrip("_")
    for pattern, label in PREFIX_RULES:
        if pattern.match(name):
            return label
    for pattern, label in SUFFIX_RULES:
        if pattern.match(name):
            return label
    if not base:
        return "other"
    if "-" in name:
        return "kebab-case"
    if "_" in base:
        if base.isupper():
            return "SCREAMING_SNAKE"
        if base.islower():
            return "snake_case"
        return "mixed_snake"
    if base.isupper() and len(base) > 1:
        return "SCREAMING_SNAKE"
    if base[0].isupper():
        return "PascalCase"
    if base[0].islower():
        return "camelCase"
    return "other"


def is_generated(path: str, text: str) -> bool:
    lowered = path.lower()
    if lowered.endswith(".min.js") or lowered.endswith(".min.css"):
        return True
    head = "\n".join(text.splitlines()[:30]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def list_files(root: str) -> list[str]:
    git_dir = os.path.join(root, ".git")
    if os.path.isdir(git_dir):
        try:
            out = subprocess.run(
                ["git", "-C", root, "ls-files"],
                capture_output=True, text=True, check=True,
            )
            return sorted(p for p in out.stdout.splitlines() if p)
        except (subprocess.CalledProcessError, FileNotFoundError):
            pass
    files = []
    for base, dirs, names in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in GENERATED_DIRS)
        for name in sorted(names):
            rel = os.path.relpath(os.path.join(base, name), root)
            files.append(rel.replace(os.sep, "/"))
    return sorted(files)


def partition_of(relpath: str) -> str:
    parts = relpath.split("/")
    return parts[0] if len(parts) > 1 else "."


def census(root: str) -> dict:
    counts: dict = defaultdict(lambda: defaultdict(lambda: defaultdict(int)))
    examples: dict = defaultdict(list)
    excluded = {"generated": 0, "non-source": 0}
    files_scanned = 0
    for rel in list_files(root):
        ext = os.path.splitext(rel)[1].lower()
        language = LANGUAGE_BY_EXT.get(ext)
        if language is None:
            if not rel.endswith((".md", ".txt")):
                excluded["non-source"] += 1
            continue
        full = os.path.join(root, rel)
        try:
            with open(full, encoding="utf-8", errors="replace") as handle:
                text = handle.read()
        except OSError:
            continue
        if is_generated(rel, text):
            excluded["generated"] += 1
            continue
        files_scanned += 1
        partition = f"{language}:{partition_of(rel)}"
        lines = text.splitlines()
        for index, line in enumerate(lines, start=1):
            if len(line) > 400:
                continue
            for kind, pattern in PATTERNS[language]:
                match = pattern.match(line)
                if not match:
                    continue
                name = next((g for g in match.groups() if g), None)
                if not name:
                    continue
                shape = classify(name)
                counts[partition][kind][shape] += 1
                key = (partition, kind, shape)
                if len(examples[key]) < 10:
                    examples[key].append(f"{rel}:{index}:{name}")
                break
    partitions = []
    for partition in sorted(counts):
        for kind in sorted(counts[partition]):
            shapes = counts[partition][kind]
            total = sum(shapes.values())
            dominant, dominant_count = max(
                sorted(shapes.items()), key=lambda item: item[1]
            )
            outliers = total - dominant_count
            outlier_examples = []
            for shape in sorted(shapes):
                if shape == dominant:
                    continue
                outlier_examples.extend(examples[(partition, kind, shape)])
            partitions.append(
                {
                    "partition": partition,
                    "kind": kind,
                    "total": total,
                    "dominant": dominant,
                    "dominant_count": dominant_count,
                    "share": round(dominant_count / total * 100, 1),
                    "outliers": outliers,
                    "shapes": dict(sorted(shapes.items())),
                    "outlier_examples": sorted(outlier_examples)[:10],
                }
            )
    return {
        "root": os.path.abspath(root),
        "files_scanned": files_scanned,
        "excluded": excluded,
        "partitions": partitions,
    }


def render_table(result: dict) -> str:
    lines = [
        "| Partition | Kind | Dominant | Share | Outliers | Total |",
        "|-----------|------|----------|-------|----------|-------|",
    ]
    for row in result["partitions"]:
        share = f"{row['dominant_count']}/{row['total']} {row['share']}%"
        lines.append(
            f"| {row['partition']} | {row['kind']} | {row['dominant']} | "
            f"{share} | {row['outliers']} | {row['total']} |"
        )
    lines.append(
        f"files_scanned={result['files_scanned']} "
        f"generated_excluded={result['excluded']['generated']}"
    )
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Deterministic identifier-shape census per language partition."
    )
    parser.add_argument("root", help="repository root to census")
    parser.add_argument("--json", action="store_true", help="emit JSON instead of a table")
    args = parser.parse_args(argv)
    if not os.path.isdir(args.root):
        print(f"error: not a directory: {args.root}", file=sys.stderr)
        return 2
    result = census(args.root)
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(render_table(result))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
